import type { MaterialLineItem, PurchaseRequisition } from '../types/pr'
import { createId } from '../utils/ids'

function line(
  code: string,
  name: string,
  quantity: number,
  unit: string,
  requiredDate: string,
  remarks: string,
): MaterialLineItem {
  return {
    id: createId('LINE'),
    materialCode: code,
    materialName: name,
    quantity,
    unit,
    requiredDate,
    remarks,
  }
}

